// Same hand-rolled CSV parser as the site's client-side JS (handles quoted
// multi-line fields), ported as-is so behavior matches exactly.
function parseCSV(csv) {
  const posts = [];
  let pos = 0;

  function readField() {
    let field = '';
    let inQuotes = false;

    if (csv[pos] === '"') {
      inQuotes = true;
      pos++;
    }

    while (pos < csv.length) {
      const char = csv[pos];

      if (inQuotes) {
        if (char === '"') {
          if (csv[pos + 1] === '"') {
            field += '"';
            pos += 2;
          } else {
            pos++;
            inQuotes = false;
          }
        } else {
          field += char;
          pos++;
        }
      } else {
        if (char === ',' || char === '\n' || char === '\r') {
          break;
        }
        field += char;
        pos++;
      }
    }

    return field.trim();
  }

  function readRow() {
    const fields = [];
    while (pos < csv.length) {
      fields.push(readField());

      if (csv[pos] === ',') {
        pos++;
      } else if (csv[pos] === '\r') {
        pos++;
        if (csv[pos] === '\n') pos++;
        break;
      } else if (csv[pos] === '\n') {
        pos++;
        break;
      } else {
        break;
      }
    }
    return fields;
  }

  const headers = readRow().map(h => (h === 'publishedDate' ? 'publishDate' : h));

  while (pos < csv.length) {
    while (pos < csv.length && (csv[pos] === '\n' || csv[pos] === '\r')) {
      pos++;
    }
    if (pos >= csv.length) break;

    const values = readRow();
    if (values.length === 0 || (values.length === 1 && values[0] === '')) continue;

    const post = {};
    headers.forEach((header, index) => {
      post[header] = values[index] || '';
    });

    if (post.published && post.published.toUpperCase() === 'TRUE') {
      posts.push(post);
    }
  }

  return posts;
}

const GENERATED_MARKER = '<!-- Generated by scripts/generate-blog-posts.js - edit insights/post/index.html instead -->';

function escapeAttr(str) {
  return String(str || '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

// split/join instead of String.replace so "$" in sheet content is never
// treated as a replacement pattern. Throws if the template anchor is gone,
// so a template edit can't silently produce pages with placeholder metadata.
function replaceAll(html, anchor, value) {
  if (!html.includes(anchor)) {
    throw new Error(`Template anchor not found: ${anchor}`);
  }
  return html.split(anchor).join(value);
}

function buildPage(template, post) {
  const metaTitle = (post.metaTitle && post.metaTitle.trim()) || FALLBACK_META_TITLES[post.slug] || post.title;
  const titleTag = escapeAttr(`${metaTitle} | EVERYAISLE`);
  const description = escapeAttr(post.excerpt || '');
  const image = escapeAttr(post.featuredImage || `${SITE_URL}/content/og/everyaisle-og.png`);
  const url = escapeAttr(`${SITE_URL}/insights/post/${post.slug}/`);

  let html = template;
  html = replaceAll(html, '<!DOCTYPE html>', `<!DOCTYPE html>\n${GENERATED_MARKER}`);
  html = replaceAll(html, '<title>Title | EVERYAISLE</title>', `<title>${titleTag}</title>`);
  // Appears 3x: meta description, og:description, twitter:description.
  html = replaceAll(html, 'News, insights, and resources from EVERYAISLE on AI-powered grocery and personalized shopping.', description);
  html = replaceAll(html, 'content="Title | EVERYAISLE"', `content="${titleTag}"`);
  html = replaceAll(html, 'content="https://everyaisle.com/content/og/everyaisle-og.png"', `content="${image}"`);
  html = replaceAll(html, '<meta property="og:type" content="article">',
    `<meta property="og:type" content="article">\n  <link rel="canonical" href="${url}">\n  <meta property="og:url" content="${url}">`);
  return html;
}

async function main() {
  console.log('Fetching sheet CSV...');
  const response = await fetch(GOOGLE_SHEET_CSV_URL);
  if (!response.ok) throw new Error(`Failed to fetch sheet: ${response.status}`);
  const csv = await response.text();

  const posts = parseCSV(csv);
  console.log(`Found ${posts.length} published post(s).`);

  const template = fs.readFileSync(TEMPLATE_PATH, 'utf8');
  const slugs = new Set();

  for (const post of posts) {
    if (!post.slug) {
      console.warn('Skipping row with empty slug:', post.title);
      continue;
    }
    slugs.add(post.slug);
    const html = buildPage(template, post);
    const dir = path.join(OUTPUT_ROOT, post.slug);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'index.html'), html);
    console.log(`Generated insights/post/${post.slug}/index.html`);
  }

  // Remove pages for posts that were unpublished or renamed in the sheet.
  // Only touches folders this script generated (identified by the marker).
  for (const entry of fs.readdirSync(OUTPUT_ROOT, { withFileTypes: true })) {
    if (!entry.isDirectory() || slugs.has(entry.name)) continue;
    const file = path.join(OUTPUT_ROOT, entry.name, 'index.html');
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8').includes(GENERATED_MARKER)) {
      fs.rmSync(path.join(OUTPUT_ROOT, entry.name), { recursive: true });
      console.log(`Removed stale insights/post/${entry.name}/`);
    }
  }

  console.log('Done.');
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
