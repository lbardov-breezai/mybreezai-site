// Generates a real static HTML file per blog post at
// insights/post/<slug>/index.html, so each post ships with its actual
// title/description/image already baked into the raw HTML (needed for
// social share previews and any crawler that doesn't execute JavaScript).
//
// The shared template at insights/post/index.html still works exactly as
// before for old #slug hash links - this script only adds new files, it
// doesn't change how that template renders.
//
// Run with: node scripts/generate-blog-posts.js

